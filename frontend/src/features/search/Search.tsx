import { useState } from 'react';
import { useMutation, useQuery } from '@tanstack/react-query';
import { Link } from 'react-router';
import { motion } from 'framer-motion';
import { Copy, Search as SearchIcon } from 'lucide-react';
import { toast } from 'sonner';
import { Bone, ErrorState, PageHeader, useDelayed } from '@/components/common/states';
import { Button } from '@/components/ui/button';
import { api, ApiError } from '@/lib/api';
import { DASH, dateTimeIST } from '@/lib/format';
import { qk } from '@/lib/queryKeys';
import { SQL_COLOR, tokenizeSql } from '@/lib/sqlHighlight';
import type { SearchResult } from '@/lib/types';
import { cn } from '@/lib/utils';
import { AIExplanation } from './AIExplanation';

const MONO_COLS = new Set(['src_ip', 'dst_ip', 'src_port', 'dst_port', 'time']);

function SearchBox({ value, onChange, onSubmit, pending }: { value: string; onChange: (v: string) => void; onSubmit: () => void; pending: boolean }) {
  return (
    <form className="flex gap-2 sm:gap-3" onSubmit={(e) => { e.preventDefault(); onSubmit(); }}>
      <label htmlFor="q" className="sr-only">Question</label>
      <input id="q" value={value} onChange={(e) => onChange(e.target.value)} autoComplete="off"
        placeholder="Try “Show recent events”, “Show SSH logs” or an IP address"
        className="h-14 min-w-0 flex-1 rounded-control border border-rule bg-surface px-4 text-body-lg text-ink placeholder:text-muted-foreground focus-visible:border-seal" />
      <Button type="submit" size="lg" className="h-14 px-4 sm:px-8" disabled={pending || !value.trim()}>{pending ? 'Asking…' : 'Ask'}</Button>
    </form>
  );
}

function SuggestedQuestions({ items, onPick, disabled, emphasised }: { items: string[]; onPick: (q: string) => void; disabled: boolean; emphasised: boolean }) {
  return (
    <div className="mt-3 flex flex-wrap items-center gap-2">
      <span className="text-body text-graphite">Try:</span>
      {items.map((q) => (
        <button key={q} type="button" disabled={disabled} onClick={() => onPick(q)}
          className={cn('min-h-10 max-w-full rounded-pill border px-4 py-2 text-body transition-colors duration-fast disabled:opacity-50',
            emphasised ? 'border-seal bg-seal-tint text-ink hover:bg-surface' : 'border-rule bg-surface hover:border-ink')}>
          {q}
        </button>
      ))}
    </div>
  );
}

function SqlBlock({ r }: { r: SearchResult }) {
  return (
    <div>
      <div className="mb-2 flex flex-wrap items-center justify-between gap-4 text-body">
        <span className="font-medium">
          {r.result_type === 'incidents' ? 'Detected incidents · local search · read-only' : r.engine === 'llm' ? `Generated by AI · ${r.model} · read-only` : 'Generated by query templates · read-only'}
        </span>
        <span className="font-mono text-mono text-graphite">{r.clock_caption}</span>
      </div>
      <div className="relative rounded-panel border border-rule bg-paper-sunk p-4 pr-14">
        <pre className="overflow-x-auto break-words font-mono text-mono-lg whitespace-pre-wrap">
          {tokenizeSql(r.sql).map((t, i) => <span key={i} style={{ color: SQL_COLOR[t.type] }}>{t.text}</span>)}
        </pre>
        <Button variant="ghost" size="icon" className="absolute top-2 right-2" aria-label="Copy SQL"
          onClick={() => navigator.clipboard?.writeText(r.sql).then(() => toast('SQL copied'), () => {})}>
          <Copy className="size-4" aria-hidden />
        </Button>
      </div>
    </div>
  );
}

function cell(col: string, v: string | number | null) {
  if (v == null) return DASH;
  return col === 'time' && typeof v === 'number' ? dateTimeIST(v) : String(v);
}

function ResultsTable({ columns, rows }: { columns: string[]; rows: (string | number | null)[][] }) {
  const label = (c: string) => (c === 'time' ? 'Date / time IST' : c);
  return (
    <motion.div initial={{ opacity: 0 }} animate={{ opacity: 1 }} transition={{ duration: 0.2 }}
      className="max-h-[60dvh] min-h-[240px] overflow-auto rounded-panel border border-rule bg-surface">
      <table className="w-full border-collapse text-body">
        <thead className="sticky top-0 bg-surface shadow-e1">
          <tr>{columns.map((c) => <th key={c} scope="col" className="h-11 px-4 text-left text-label font-medium text-graphite">{label(c)}</th>)}</tr>
        </thead>
        <tbody>
          {rows.map((row, i) => (
            <tr id={`search-row-${i + 1}`} aria-label={`Row ${i + 1}`} key={i} className="h-11 border-t border-rule hover:bg-paper-sunk">
              {row.map((v, j) => (
                <td key={j} className={cn('px-4', MONO_COLS.has(columns[j]) && 'font-mono text-mono')}>{cell(columns[j], v)}</td>
              ))}
            </tr>
          ))}
        </tbody>
      </table>
    </motion.div>
  );
}

export default function Search() {
  const [question, setQuestion] = useState('');
  const [useAI, setUseAI] = useState(false);
  const [followUp, setFollowUp] = useState(false);
  const [previous, setPrevious] = useState<SearchResult | null>(null);
  const status = useQuery({ queryKey: ['ai-status'], queryFn: api.ai.status, staleTime: 60_000 });
  const sugg = useQuery({ queryKey: qk.suggestions, queryFn: api.search.suggestions });
  const m = useMutation({ mutationFn: (q: string) => api.search.ask(q, {
    use_ai: useAI, consent: useAI, previous_id: useAI && followUp ? previous?.query_id : undefined,
  }), onSuccess: (result) => setPrevious(result) });
  const showLoading = useDelayed(m.isPending);
  const suggestions = sugg.data?.items ?? [];
  const ask = (q: string) => { if (q.trim()) m.mutate(q.trim()); };
  const r = m.data;
  const err = m.error as ApiError | null;

  return (
    <div>
      <PageHeader title="Ask the evidence" />
      <p className="mb-4 text-body text-graphite">Search your private workspace. Try “Show detected incidents” for suspicious activity, or search recent events, devices, IP addresses, SSH logs and login results.</p>
      <div className="mb-4 space-y-2 rounded-panel border border-rule bg-surface p-4 text-body">
        <label className="flex items-start gap-2"><input type="checkbox" className="mt-1" checked={useAI} disabled={!status.data?.configured || m.isPending}
          onChange={(e) => { setUseAI(e.target.checked); setFollowUp(false); }} />Use Gemini AI search. I authorize sending my question, search schema and (for follow-ups) the previous question and SQL to Google. Result rows are not sent for search.</label>
        {!status.data?.configured && <p className="text-graphite">{status.isPending ? 'Checking AI availability…' : status.isError ? 'Could not check AI availability; built-in search remains available.' : 'Hosted AI is not configured. Built-in search remains available.'}</p>}
        {useAI && <>
          <p className="text-graphite">Avoid sensitive information in questions. Free-tier processing may use submitted data to improve Google products. Try “Show failed SSH logins from yesterday.” AI may misinterpret your request: review the SQL and time window.</p>
          {previous?.query_id && <label className="flex items-start gap-2"><input type="checkbox" className="mt-1" checked={followUp} disabled={m.isPending} onChange={(e) => setFollowUp(e.target.checked)} />Follow up on “{previous.question}” (context expires after 10 minutes). Uncheck to start a new search.</label>}
        </>}
      </div>
      <SearchBox value={question} onChange={setQuestion} onSubmit={() => ask(question)} pending={m.isPending} />
      <SuggestedQuestions items={suggestions} disabled={m.isPending} emphasised={!r && !m.isPending}
        onPick={(q) => { setQuestion(q); ask(q); }} />
      <div className="mt-6 border-t border-rule pt-6">
        {m.isPending && showLoading ? (
          <div aria-busy="true"><p className="mb-2 text-body font-medium">Writing SQL…</p><Bone className="h-24" /></div>
        ) : err ? (
          err.code === 'unanswerable' && !err.detail?.reason ? (
            <div className="rounded-panel border border-rule bg-surface p-5">
              <p className="text-body-lg">This wording is not supported by the built-in search. Try a suggestion below, “Show failed logins”, or an IP address.</p>
              <SuggestedQuestions items={suggestions} disabled={false} emphasised onPick={(q) => { setQuestion(q); ask(q); }} />
            </div>
          ) : (
            <ErrorState title={err.code === 'unanswerable' ? 'That question took too long.' : "Couldn't run that question."}
              body={err.code === 'unanswerable' ? 'Try narrowing the time window.' : err.message}
              onRetry={() => ask(question)} code={err.code} />
          )
        ) : r ? (
          <div className="space-y-4">
            <SqlBlock r={r} />
            <p className="text-body text-graphite tabular">{r.row_count} {r.result_type === 'incidents' ? 'incidents' : 'rows'}{r.row_count === 200 ? ' (display limit reached)' : ''} · {(r.took_ms / 1000).toFixed(1)} s</p>
            {r.result_type === 'incidents' ? <div className="space-y-3">
              <p className="text-body text-graphite">These are findings detected by ANVAYA's correlation rules, not confirmed intrusions. Open an incident to inspect its evidence and request an AI explanation.</p>
              {!r.incidents?.length && <p className="text-body-lg">No detected incidents match these filters. This does not establish that your systems are secure.</p>}
              {r.incidents?.map((incident) => <Link key={incident.incident_id} to={`/incidents/${incident.incident_id}`} className="block space-y-2 rounded-panel border border-rule bg-surface p-4 hover:border-seal">
                <h2 className="text-h3 font-semibold text-seal">{incident.title}</h2>
                <p className="text-body">{incident.level} · Risk {incident.risk} · {incident.event_count} linked events · {incident.devices.join(', ')}</p>
                <p className="text-body text-graphite">{dateTimeIST(incident.first_time)} – {dateTimeIST(incident.last_time)} · {incident.status}</p>
                <span className="text-body underline">Open incident and evidence</span>
              </Link>)}
            </div> : r.row_count === 0 ? (
              <div className="space-y-3">
                <p className="text-body-lg">No matching normalized events for this query.</p>
                <p className="text-body text-graphite">Time windows use the original event timestamp. Older imported logs may be outside the last hour. Quarantined records are not searchable here.</p>
                <Button variant="outline" onClick={() => { setQuestion('Show recent events'); ask('Show recent events'); }}>Show latest stored events across all dates</Button>
              </div>
            ) : (
              <ResultsTable columns={r.columns} rows={r.rows} />
            )}
            {r.result_type !== 'incidents' && r.row_count > 0 && r.query_id && <AIExplanation key={r.query_id} kind="search" target={r.query_id} />}
          </div>
        ) : (
          <p className="flex items-start gap-2 text-body text-graphite">
            <SearchIcon className="size-5" aria-hidden />
            Answers come from normalized events only. Queries are read-only and run on the ANVAYA server. “Show recent events” returns the latest 200 stored events across all dates.
          </p>
        )}
      </div>
    </div>
  );
}
